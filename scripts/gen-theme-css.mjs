#!/usr/bin/env node
// Generates src/app/theme-light.css, the light theme for a codebase written dark-first.
//
// Approach (no per-component edits):
//  1. At the html root, the neutral (slate) scale is inverted and the deep hue shades (800/900/950) become pale tints,
//     by redefining Tailwind's own colour variables. Every bg-/border-/from-/text-slate utility flips automatically.
//  2. Pale accent text (text-teal-300 ...) points at an "ink" variable that is a readable dark shade in light mode.
//  3. Inside a saturated fill (bg-teal-600, from-indigo-500 ...) every variable above is restored to its original
//     value, so buttons, badges and gradient heroes keep the dark-theme look their text was designed for.
//
// Run:  node scripts/gen-theme-css.mjs          (writes the file)
//       node scripts/gen-theme-css.mjs --check  (exit 1 when the committed file is stale; used by tests)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(import.meta.url);
const root = path.resolve(path.dirname(here), '..');
const OUT = path.join(root, 'src/app/theme-light.css');
const HUES = ['teal', 'indigo', 'emerald', 'rose', 'red', 'amber', 'yellow', 'orange', 'blue', 'sky', 'cyan', 'purple', 'violet', 'pink', 'green', 'lime', 'fuchsia'];
const SLATE_SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

// The neutral scale, inverted for a light page: page = slate-900, raised card = slate-800.
const SLATE_LIGHT = {
  50: '#0f172a', 100: '#1e293b', 200: '#1e293b', 300: '#334155', 400: '#475569', 500: '#5b6b82',
  600: '#cbd5e1', 700: '#e2e8f0', 800: '#ffffff', 900: '#f1f5f9', 950: '#f8fafc',
};

const THEME = readFileSync(path.join(root, 'node_modules/tailwindcss/theme.css'), 'utf8');
function colour(hue, shade) {
  const m = THEME.match(new RegExp(`--color-${hue}-${shade}:\\s*([^;]+);`));
  if (!m) throw new Error(`Tailwind theme has no ${hue}-${shade}`);
  return m[1].trim();
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.(tsx|ts)$/.test(name)) out.push(full);
  }
  return out;
}

const tail = '(?![\\w/-])';
const escapeClass = token => token.replace(/[:/]/g, ch => `\\${ch}`);

export function generate() {
  const files = walk(path.join(root, 'src')).filter(f => !f.endsWith('theme-light.css')).map(f => readFileSync(f, 'utf8'));
  const source = files.join('\n');

  // Pale accent text actually used in the app, with any variant prefix and opacity suffix.
  const paleRe = new RegExp(`(?<![\\w-])((?:hover:|focus:|group-hover:|disabled:)?)text-(${HUES.join('|')})-(100|200|300|400)(?:/(\\d+))?${tail}`, 'g');
  const pale = new Map(); // token -> { variant, hue, shade, alpha }
  for (const m of source.matchAll(paleRe)) pale.set(m[0], { variant: m[1], hue: m[2], shade: Number(m[3]), alpha: m[4] });
  const inks = [...new Set([...pale.values()].map(p => `${p.hue}-${p.shade}`))].sort();

  // Saturated fills, only for hues/shades that exist in the source, to keep the selector list small.
  const fillRe = new RegExp(`(?<![\\w-])(bg|from|via|to)-(${HUES.join('|')})-(300|400|500|600|700)${tail}`, 'g');
  const fills = new Set();
  for (const m of source.matchAll(fillRe)) fills.add(`.${m[1]}-${m[2]}-${m[3]}`);
  const fillSelector = [...fills].sort().map(c => `html[data-theme="light"] ${c}`).join(',\n');

  const out = [];
  out.push('/* GENERATED by scripts/gen-theme-css.mjs. Do not edit by hand. */', '');

  out.push('html[data-theme="light"] {', '  color-scheme: light;');
  for (const shade of SLATE_SHADES) out.push(`  --color-slate-${shade}: ${SLATE_LIGHT[shade]};`);
  out.push('  --color-white: #0f172a;');
  for (const hue of HUES) {
    out.push(`  --color-${hue}-950: ${colour(hue, 50)};`, `  --color-${hue}-900: ${colour(hue, 100)};`, `  --color-${hue}-800: ${colour(hue, 200)};`);
  }
  for (const ink of inks) { const [hue] = ink.split('-'); out.push(`  --ink-${ink}: ${colour(hue, 800)};`); }
  out.push('}', '');

  out.push('/* Page chrome that is not a utility class. */');
  out.push('html[data-theme="light"] body { background-color: #f1f5f9; color: #1e293b; }', '');

  out.push('/* Inside a saturated fill, restore the original (dark-theme) values its text was designed for. */');
  out.push(`${fillSelector} {`, '  --color-white: #ffffff;');
  for (const shade of SLATE_SHADES) out.push(`  --color-slate-${shade}: ${colour('slate', shade)};`);
  for (const hue of HUES) out.push(`  --color-${hue}-950: ${colour(hue, 950)};`, `  --color-${hue}-900: ${colour(hue, 900)};`, `  --color-${hue}-800: ${colour(hue, 800)};`);
  for (const ink of inks) { const [hue, shade] = ink.split('-'); out.push(`  --ink-${ink}: ${colour(hue, shade)};`); }
  out.push('}', '');

  // A deep fill with no text colour of its own would inherit the dark page ink; give it white.
  const deep = [...fills].filter(c => /-(500|600|700)$/.test(c) && c.startsWith('.bg-'));
  out.push('/* Deep fills with no text colour of their own read white. */');
  out.push(`${deep.sort().map(c => `html[data-theme="light"] ${c}:not([class*="text-"])`).join(',\n')} { color: #ffffff; }`, '');

  out.push('/* Pale accent text resolves through its ink variable. */');
  for (const token of [...pale.keys()].sort()) {
    const { variant, hue, shade, alpha } = pale.get(token);
    const value = alpha ? `color-mix(in oklab, var(--ink-${hue}-${shade}) ${alpha}%, transparent)` : `var(--ink-${hue}-${shade})`;
    const pseudo = { 'hover:': ':hover', 'focus:': ':focus', 'disabled:': ':disabled' }[variant] || '';
    const prefix = variant === 'group-hover:' ? '.group:hover ' : '';
    out.push(`html[data-theme="light"] ${prefix}.${escapeClass(token)}${pseudo} { color: ${value}; }`);
  }
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === here) {
  const css = generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (current !== css) { console.error('src/app/theme-light.css is stale. Run: node scripts/gen-theme-css.mjs'); process.exit(1); }
    console.log('theme-light.css is up to date.');
  } else {
    writeFileSync(OUT, css);
    console.log(`Wrote ${path.relative(root, OUT)} (${css.split('\n').length} lines, ${(css.length / 1024).toFixed(1)} KB)`);
  }
}
